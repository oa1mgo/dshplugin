export const SUPPORTED_LANGUAGE_CODES = Object.freeze(Object.keys(messages));

export function resolveSupportedLanguage(languages = []) {
  for (const language of languages) {
    const normalized = String(language).toLowerCase();
    if (normalized.startsWith("zh")) return "zh-CN";
    if (normalized.startsWith("ja")) return "ja";
    if (normalized.startsWith("ko")) return "ko";
    if (normalized.startsWith("es")) return "es";
    if (normalized.startsWith("en")) return "en";
  }
  return DEFAULT_LANGUAGE;
}

export function translate(locale, key, variables = {}) {
  const template = messages[locale]?.[key] ?? messages.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name) => String(variables[name] ?? `{${name}}`));
}
